  await expect(dialog.getByRole('status')).toContainText('Use um SVG autocontido');
  await expect(sidebar.getByRole('img', { name: 'Edgar Studio' })).toBeVisible();
  await page.screenshot({ path: 'test-results/logo-studio-desktop.png', fullPage: true });
