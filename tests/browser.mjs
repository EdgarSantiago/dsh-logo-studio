  assert.equal(await sidebar.locator('.dsh-logo-mark-hidden').evaluate(node => getComputedStyle(node.parentElement.parentElement).display), 'none');
  await page.getByRole('button', { name: 'Recolher', exact: true }).click();
  await expect(sidebar.locator('img')).toBeVisible();
  await page.getByRole('button', { name: 'Expandir', exact: true }).click();
  await page.getByRole('button', { name: 'Personalizar logo' }).click();
