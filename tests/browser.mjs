  await expect(sidebar.getByText('Edgar Studio')).toHaveCount(0);
  await page.getByRole('button', { name: 'Salvar alterações' }).click();
  await expect(sidebar.getByText('Edgar Studio')).toBeVisible();
  // A light layer token can appear in dark/custom themes. The badge must not
  // borrow that token as text color over its inherited light fill.
  await page.evaluate(() => document.documentElement.style.setProperty('--dsw-alias-bg-layer-2', '#eeeeee'));
  const contrast = await sidebar.locator('.dsh-logo-badge').evaluate(node => {
    const background = getComputedStyle(node).backgroundColor;
    const foreground = getComputedStyle(node.querySelector('span')).color;
    const luminance = value => value.match(/[\d.]+/g).slice(0, 3).map(Number).map(channel => {
      const v = channel / 255;
      return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
    }).reduce((total, value, index) => total + value * [0.2126, 0.7152, 0.0722][index], 0);
    const a = luminance(background), b = luminance(foreground);
    return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
  });
  assert.ok(contrast >= 4.5, `Badge contrast must remain readable with custom theme tokens: ${contrast}`);
  const savedBeforeContrast = await page.evaluate(() => localStorage.getItem('dsh-logo-studio:v1'));
  await sidebar.evaluate(node => { node.style.background = '#f4f4f5'; });
  await expect(sidebar.locator('.dsh-logo-name')).toHaveCSS('color', 'rgb(0, 0, 0)');
  await sidebar.evaluate(node => { node.style.background = '#1b1b1f'; });
  await expect(sidebar.locator('.dsh-logo-name')).toHaveCSS('color', 'rgb(238, 238, 238)');
  assert.equal(await page.evaluate(() => localStorage.getItem('dsh-logo-studio:v1')), savedBeforeContrast);
  await sidebar.screenshot({ path: 'test-results/logo-studio-badge.png' });
  await page.evaluate(() => document.documentElement.style.setProperty('--dsw-alias-bg-layer-2', '#222222'));
  await page.reload(); await expect(sidebar.getByText('Edgar Studio')).toBeVisible();
  await page.getByRole('button', { name: 'Personalizar logo' }).click();
  await page.getByLabel('Nome da marca').fill('Not saved');
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(sidebar.getByText('Edgar Studio')).toBeVisible();
  await page.getByRole('button', { name: 'Personalizar logo' }).click();
  await page.getByLabel('Estilo da logo').selectOption('image');
  await page.getByLabel('Enviar logo', { exact: true }).setInputFiles({ name: 'test.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="400" height="80"><rect width="400" height="80" rx="16" fill="#8761ff"/><text x="24" y="54" font-size="40" fill="white">EDGAR STUDIO</text></svg>') });
  await expect(page.getByText('Processando imagem…')).toHaveCount(0);
  await expect(dialog.locator('.ls-preview img')).toHaveCount(2);
